import '../../domain/entities/app_settings.dart';
import '../../domain/entities/privacy_settings.dart';
import '../../domain/entities/profile_entity.dart';
import '../../domain/entities/verification_status.dart';

class ProfileModel extends ProfileEntity {
  const ProfileModel({
    required super.uid,
    required super.username,
    required super.displayName,
    super.bio,
    super.location,
    super.gender,
    super.birthday,
    super.phone,
    super.email,
    super.website,
    super.isOnline,
    super.lastSeen,
    super.avatarUrl,
    super.avatarPublicId,
    super.coverUrl,
    super.coverPublicId,
    super.friendsCount,
    super.groupsCount,
    super.verificationStatus,
    super.createdAt,
    super.notificationsEnabled,
    super.profilePrivacy,
    super.lastSeenVisibility,
    super.onlineStatusVisibility,
    super.friendRequestPrivacy,
    super.themeMode,
    super.enterToSend,
    super.readReceiptsEnabled,
    super.typingIndicatorEnabled,
    super.autoDownloadImages,
    super.autoDownloadVideos,
    super.autoDownloadFiles,
    super.mediaWifiOnly,
  });

  factory ProfileModel.fromSupabaseRows({
    required String uid,
    required Map<String, dynamic> userRow,
    Map<String, dynamic>? settingsRow,
    Map<String, dynamic>? presenceRow,
  }) {
    DateTime? parseDate(dynamic raw) => raw is String ? DateTime.tryParse(raw)?.toLocal() : null;

    return ProfileModel(
      uid: uid,
      username: userRow['username'] as String? ?? '',
      displayName: userRow['display_name'] as String? ?? '',
      bio: userRow['bio'] as String?,
      location: userRow['location'] as String?,
      gender: userRow['gender'] as String?,
      birthday: parseDate(userRow['birthday']),
      phone: userRow['phone'] as String?,
      email: userRow['email'] as String?,
      website: userRow['website'] as String?,
      isOnline: presenceRow?['is_online'] as bool? ?? false,
      lastSeen: parseDate(presenceRow?['last_seen']),
      avatarUrl: userRow['avatar_url'] as String?,
      avatarPublicId: userRow['avatar_public_id'] as String?,
      coverUrl: userRow['cover_url'] as String?,
      coverPublicId: userRow['cover_public_id'] as String?,
      friendsCount: userRow['friends_count'] as int? ?? 0,
      groupsCount: userRow['groups_count'] as int? ?? 0,
      verificationStatus: verificationStatusFromString(userRow['verification_status'] as String?),
      createdAt: parseDate(userRow['created_at']),
      notificationsEnabled: settingsRow?['notifications_enabled'] as bool? ?? true,
      profilePrivacy: privacyOptionFromString(settingsRow?['profile_privacy'] as String?),
      lastSeenVisibility: privacyOptionFromString(settingsRow?['last_seen_visibility'] as String?),
      onlineStatusVisibility: privacyOptionFromString(settingsRow?['online_status_visibility'] as String?),
      friendRequestPrivacy: friendRequestPrivacyFromString(settingsRow?['friend_request_privacy'] as String?),
      themeMode: appThemeModePrefFromString(settingsRow?['theme_mode'] as String?),
      enterToSend: settingsRow?['enter_to_send'] as bool? ?? true,
      readReceiptsEnabled: settingsRow?['read_receipts_enabled'] as bool? ?? true,
      typingIndicatorEnabled: settingsRow?['typing_indicator_enabled'] as bool? ?? true,
      autoDownloadImages: settingsRow?['auto_download_images'] as bool? ?? true,
      autoDownloadVideos: settingsRow?['auto_download_videos'] as bool? ?? false,
      autoDownloadFiles: settingsRow?['auto_download_files'] as bool? ?? false,
      mediaWifiOnly: settingsRow?['media_wifi_only'] as bool? ?? true,
    );
  }

  ProfileModel mergeUsersRow(Map<String, dynamic> userRow) {
    final merged = ProfileModel.fromSupabaseRows(uid: uid, userRow: userRow);
    return copyWithModel(
      username: merged.username,
      displayName: merged.displayName,
      bio: merged.bio,
      location: merged.location,
      gender: merged.gender,
      birthday: merged.birthday,
      phone: merged.phone,
      email: merged.email,
      website: merged.website,
      avatarUrl: merged.avatarUrl,
      avatarPublicId: merged.avatarPublicId,
      coverUrl: merged.coverUrl,
      coverPublicId: merged.coverPublicId,
      friendsCount: merged.friendsCount,
      groupsCount: merged.groupsCount,
      verificationStatus: merged.verificationStatus,
      createdAt: merged.createdAt,
    );
  }

  ProfileModel mergeSettingsRow(Map<String, dynamic> settingsRow) {
    final merged = ProfileModel.fromSupabaseRows(uid: uid, userRow: const {}, settingsRow: settingsRow);
    return copyWithModel(
      notificationsEnabled: merged.notificationsEnabled,
      profilePrivacy: merged.profilePrivacy,
      lastSeenVisibility: merged.lastSeenVisibility,
      onlineStatusVisibility: merged.onlineStatusVisibility,
      friendRequestPrivacy: merged.friendRequestPrivacy,
      themeMode: merged.themeMode,
      enterToSend: merged.enterToSend,
      readReceiptsEnabled: merged.readReceiptsEnabled,
      typingIndicatorEnabled: merged.typingIndicatorEnabled,
      autoDownloadImages: merged.autoDownloadImages,
      autoDownloadVideos: merged.autoDownloadVideos,
      autoDownloadFiles: merged.autoDownloadFiles,
      mediaWifiOnly: merged.mediaWifiOnly,
    );
  }

  ProfileModel mergePresenceRow(Map<String, dynamic> presenceRow) {
    final merged = ProfileModel.fromSupabaseRows(uid: uid, userRow: const {}, presenceRow: presenceRow);
    return copyWithModel(isOnline: merged.isOnline, lastSeen: merged.lastSeen, clearLastSeen: merged.lastSeen == null);
  }

  ProfileModel copyWithModel({
    String? username,
    String? displayName,
    String? bio,
    String? location,
    String? gender,
    DateTime? birthday,
    String? phone,
    String? email,
    String? website,
    bool? isOnline,
    DateTime? lastSeen,
    bool clearLastSeen = false,
    String? avatarUrl,
    String? avatarPublicId,
    String? coverUrl,
    String? coverPublicId,
    int? friendsCount,
    int? groupsCount,
    VerificationStatus? verificationStatus,
    DateTime? createdAt,
    bool? notificationsEnabled,
    PrivacyOption? profilePrivacy,
    PrivacyOption? lastSeenVisibility,
    PrivacyOption? onlineStatusVisibility,
    FriendRequestPrivacy? friendRequestPrivacy,
    AppThemeModePref? themeMode,
    bool? enterToSend,
    bool? readReceiptsEnabled,
    bool? typingIndicatorEnabled,
    bool? autoDownloadImages,
    bool? autoDownloadVideos,
    bool? autoDownloadFiles,
    bool? mediaWifiOnly,
  }) {
    return ProfileModel(
      uid: uid,
      username: username ?? this.username,
      displayName: displayName ?? this.displayName,
      bio: bio ?? this.bio,
      location: location ?? this.location,
      gender: gender ?? this.gender,
      birthday: birthday ?? this.birthday,
      phone: phone ?? this.phone,
      email: email ?? this.email,
      website: website ?? this.website,
      isOnline: isOnline ?? this.isOnline,
      lastSeen: clearLastSeen ? null : (lastSeen ?? this.lastSeen),
      avatarUrl: avatarUrl ?? this.avatarUrl,
      avatarPublicId: avatarPublicId ?? this.avatarPublicId,
      coverUrl: coverUrl ?? this.coverUrl,
      coverPublicId: coverPublicId ?? this.coverPublicId,
      friendsCount: friendsCount ?? this.friendsCount,
      groupsCount: groupsCount ?? this.groupsCount,
      verificationStatus: verificationStatus ?? this.verificationStatus,
      createdAt: createdAt ?? this.createdAt,
      notificationsEnabled: notificationsEnabled ?? this.notificationsEnabled,
      profilePrivacy: profilePrivacy ?? this.profilePrivacy,
      lastSeenVisibility: lastSeenVisibility ?? this.lastSeenVisibility,
      onlineStatusVisibility: onlineStatusVisibility ?? this.onlineStatusVisibility,
      friendRequestPrivacy: friendRequestPrivacy ?? this.friendRequestPrivacy,
      themeMode: themeMode ?? this.themeMode,
      enterToSend: enterToSend ?? this.enterToSend,
      readReceiptsEnabled: readReceiptsEnabled ?? this.readReceiptsEnabled,
      typingIndicatorEnabled: typingIndicatorEnabled ?? this.typingIndicatorEnabled,
      autoDownloadImages: autoDownloadImages ?? this.autoDownloadImages,
      autoDownloadVideos: autoDownloadVideos ?? this.autoDownloadVideos,
      autoDownloadFiles: autoDownloadFiles ?? this.autoDownloadFiles,
      mediaWifiOnly: mediaWifiOnly ?? this.mediaWifiOnly,
    );
  }

  factory ProfileModel.fromCacheJson(String uid, Map<String, dynamic> json) {
    DateTime? parseMillis(dynamic raw) => raw is int ? DateTime.fromMillisecondsSinceEpoch(raw) : null;

    return ProfileModel(
      uid: uid,
      username: json['username'] as String? ?? '',
      displayName: json['displayName'] as String? ?? '',
      bio: json['bio'] as String?,
      location: json['location'] as String?,
      gender: json['gender'] as String?,
      birthday: parseMillis(json['birthday']),
      phone: json['phone'] as String?,
      email: json['email'] as String?,
      website: json['website'] as String?,
      isOnline: json['isOnline'] as bool? ?? false,
      lastSeen: parseMillis(json['lastSeen']),
      avatarUrl: json['avatarUrl'] as String?,
      avatarPublicId: json['avatarPublicId'] as String?,
      coverUrl: json['coverUrl'] as String?,
      coverPublicId: json['coverPublicId'] as String?,
      friendsCount: json['friendsCount'] as int? ?? 0,
      groupsCount: json['groupsCount'] as int? ?? 0,
      verificationStatus: verificationStatusFromString(json['verificationStatus'] as String?),
      createdAt: parseMillis(json['createdAt']),
      notificationsEnabled: json['notificationsEnabled'] as bool? ?? true,
      profilePrivacy: privacyOptionFromString(json['profilePrivacy'] as String?),
      lastSeenVisibility: privacyOptionFromString(json['lastSeenVisibility'] as String?),
      onlineStatusVisibility: privacyOptionFromString(json['onlineStatusVisibility'] as String?),
      friendRequestPrivacy: friendRequestPrivacyFromString(json['friendRequestPrivacy'] as String?),
      themeMode: appThemeModePrefFromString(json['themeMode'] as String?),
      enterToSend: json['enterToSend'] as bool? ?? true,
      readReceiptsEnabled: json['readReceiptsEnabled'] as bool? ?? true,
      typingIndicatorEnabled: json['typingIndicatorEnabled'] as bool? ?? true,
      autoDownloadImages: json['autoDownloadImages'] as bool? ?? true,
      autoDownloadVideos: json['autoDownloadVideos'] as bool? ?? false,
      autoDownloadFiles: json['autoDownloadFiles'] as bool? ?? false,
      mediaWifiOnly: json['mediaWifiOnly'] as bool? ?? true,
    );
  }

  Map<String, dynamic> toCacheJson() {
    return {
      'username': username,
      'displayName': displayName,
      if (bio != null) 'bio': bio,
      if (location != null) 'location': location,
      if (gender != null) 'gender': gender,
      if (birthday != null) 'birthday': birthday!.millisecondsSinceEpoch,
      if (phone != null) 'phone': phone,
      if (email != null) 'email': email,
      if (website != null) 'website': website,
      'isOnline': isOnline,
      if (lastSeen != null) 'lastSeen': lastSeen!.millisecondsSinceEpoch,
      if (avatarUrl != null) 'avatarUrl': avatarUrl,
      if (avatarPublicId != null) 'avatarPublicId': avatarPublicId,
      if (coverUrl != null) 'coverUrl': coverUrl,
      if (coverPublicId != null) 'coverPublicId': coverPublicId,
      'friendsCount': friendsCount,
      'groupsCount': groupsCount,
      'verificationStatus': verificationStatusToString(verificationStatus),
      if (createdAt != null) 'createdAt': createdAt!.millisecondsSinceEpoch,
      'notificationsEnabled': notificationsEnabled,
      'profilePrivacy': privacyOptionToString(profilePrivacy),
      'lastSeenVisibility': privacyOptionToString(lastSeenVisibility),
      'onlineStatusVisibility': privacyOptionToString(onlineStatusVisibility),
      'friendRequestPrivacy': friendRequestPrivacyToString(friendRequestPrivacy),
      'themeMode': appThemeModePrefToString(themeMode),
      'enterToSend': enterToSend,
      'readReceiptsEnabled': readReceiptsEnabled,
      'typingIndicatorEnabled': typingIndicatorEnabled,
      'autoDownloadImages': autoDownloadImages,
      'autoDownloadVideos': autoDownloadVideos,
      'autoDownloadFiles': autoDownloadFiles,
      'mediaWifiOnly': mediaWifiOnly,
    };
  }
}
